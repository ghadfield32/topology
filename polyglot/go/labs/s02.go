package labs

func init() { register("s02", run_s02) }
func run_s02(repo string) (Result, error) {
	pts, err := loadSPLBall(repo)
	if err != nil {
		return Result{}, err
	}
	return Result{Lab: "s02", Title: "Ball-flight model adequacy", Metrics: map[string]any{"selected_ball_points": len(pts), "centroid_m": weightedMean([][][]float64{pts})}, Notes: []string{"Selected excerpt; not a full tracking corpus."}}, nil
}
