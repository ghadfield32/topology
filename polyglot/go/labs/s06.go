package labs

func init() { register("s06", run_s06) }
func run_s06(repo string) (Result, error) {
	pts, err := loadSPLBall(repo)
	if err != nil {
		return Result{}, err
	}
	return Result{Lab: "s06", Title: "Independent sports investigation", Metrics: map[string]any{"selected_ball_points": len(pts), "centroid_m": weightedMean([][][]float64{pts})}, Notes: []string{"Selected excerpt; not a full tracking corpus."}}, nil
}
