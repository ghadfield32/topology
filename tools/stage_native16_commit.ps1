#!/usr/bin/env pwsh
# Stage the native16 / language-notebook integration as an EXPLICIT path list.
#
# Deliberate choices:
#   * No `git add -A` and no `git add .`. Every path below is named.
#   * Learner work (notebooks/00..02, reports/stage_00, reports/stage_02) is NOT
#     staged. Those are Geoff's own experiments and reference-output refreshes;
#     they belong in a separate, intentional commit.
#   * The root COMPLETE_COURSE_V2..V7 deletions are NOT staged. They move content
#     to archive/ and deserve their own reasoned commit.
#   * my_work/ is git-ignored and never staged.
#   * `git add -- <paths>` stages exactly those paths; it cannot sweep the tree.
#
# Run with -Commit to also create the commit.

param([switch]$Commit)

$ErrorActionPreference = 'Stop'
Set-Location (Join-Path $PSScriptRoot '..')

$paths = @(
    '.gitignore'
    '.dockerignore'
    'README.md'
    'START_HERE.html'
    'START_NATIVE.html'
    'native_course.py'
    'polyglot.py'

    'archive'
    'native'
    'polyglot'
    'curriculum/extensions/poux_spatial_ai'
    'deploy/polyglot'
    'reports/v14'
    'workbooks/polyglot'

    'docs/v16'
    'docs/v14'
    'docs/release/NATIVE16_IMPORT.md'
    'docs/release/LANGUAGE_NOTEBOOKS.md'
    'docs/release/CHECKS.md'
    'docs/release/STAGE01_WALKTHROUGH.md'
    'docs/release/HANDOFF_REPORT.md'
    'docs/release/REPOSITORY_LAYOUT.md'

    'tools/build_language_notebooks.py'
    'tools/verify_language_notebooks.py'
    'tools/evidence_pointer.py'
    'tools/check_matrix.py'
    'tools/native_deploy_verify.py'
    'tools/checkpoint_current_state.py'
    'tools/polyglot_verify.py'
    'tools/stage_native16_commit.ps1'
    'tools/verify_fresh_checkout.ps1'

    'tests/test_native_v16.py'
    'tests/test_polyglot_v14.py'
    'tests/test_language_notebooks.py'
    'tests/test_notebook_verifier.py'
    'tests/test_learner_mutation.py'
    'tests/test_check_matrix_and_deploy.py'
    'tests/test_ci_workflows.py'
    'tests/test_repository_layout.py'

    '.github/workflows/native-course-v16.yml'
    '.github/workflows/polyglot.yml'
    '.github/workflows/language-notebooks.yml'
)

$missing = $paths | Where-Object { -not (Test-Path -LiteralPath $_) }
if ($missing) {
    Write-Host 'Refusing to stage: these paths do not exist:' -ForegroundColor Red
    $missing | ForEach-Object { Write-Host "  $_" }
    exit 3
}

Write-Host "Staging $($paths.Count) explicit paths..."
git add -- $paths
if ($LASTEXITCODE -ne 0) { throw "git add failed" }

Write-Host "`nStaged summary:" -ForegroundColor Cyan
git diff --cached --stat | Select-Object -Last 6

Write-Host "`nNOT staged (left for separate, reasoned commits):" -ForegroundColor Yellow
foreach ($skip in @('COMPLETE_COURSE_V2..V7.md (root deletions)', 'notebooks/00..02_lab.ipynb (learner edits)', 'reports/stage_00, reports/stage_02 (reference outputs)')) {
    Write-Host "  $skip"
}

if ($Commit) {
    $msg = @'
Import the native16 track and the three-language workbooks

Additive: this does not change the Python package version or uv.lock.

- native/: 57 Go and Rust learning units, bounded data readers, guides and
  evidence; both compile and pass (Go 34, Rust 28) and agree on all 57 labs.
- workbooks/polyglot/: 171 generated Python/Go/Rust notebooks plus an index.
  Python runs the canonical course reference; Go and Rust compile and run the
  real native programs. Generated by tools/build_language_notebooks.py.
- tools/: notebook generator with a real --check, the 171-entry verifier,
  explicit evidence resolution, a separated check matrix and the native
  deploy verifier.
- tests/: notebook contracts, verifier contracts, learner-mutation proof
  (fail -> repair -> pass), check-matrix/deploy safety, CI workflow contracts.
- docs/release/: import record, notebook guide, check scopes, Stage 01
  walkthrough and the handoff report.

Original 133-notebook parity remains not_certified; the guard refusing that
claim is untouched. Learner work and reference outputs are not part of this
commit.
'@
    git commit -m $msg
    if ($LASTEXITCODE -ne 0) { throw "git commit failed" }
    Write-Host "`nCommitted." -ForegroundColor Green
    git log -1 --oneline
}
