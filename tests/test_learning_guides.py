"""The hand-maintained learning guides must stay additive and factually checkable.

`learning/workbooks/` is generated by `systems/tools/generate_workbooks.py` and has its own
contract test. This module covers the *written* guides, which are hand-edited and therefore
need a different guard: they must not become a second curriculum, and the advice they give
must not contradict what the tools actually do.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GUIDE = ROOT / "learning" / "rust_from_python.md"
INDEX = ROOT / "learning" / "README.md"


def test_guide_exists_and_is_linked_from_the_learning_index():
    assert GUIDE.is_file()
    text = INDEX.read_text(encoding="utf-8")
    assert "rust_from_python.md" in text
    assert "not generated" in text.lower()
    # The original navigation claims must survive the addition.
    assert "LEARN_TOPOLOGY.html" in text
    assert "systems/tools/generate_workbooks.py" in text


def test_guide_does_not_become_a_second_curriculum():
    text = GUIDE.read_text(encoding="utf-8")
    assert "not a second curriculum" in text.lower() or "not assessed" in text.lower()
    assert "curriculum/catalog.json" in text
    assert "LEARNING_PATHS.md" in text
    # Any stage identifier it mentions must already exist in the single catalogue.
    # Catalogue ids are bare two-digit codes; prose refers to them as `stage01`.
    known = {"stage" + s["id"] for s in json.loads((ROOT / "curriculum/catalog.json").read_text(encoding="utf-8"))["stages"]}
    mentioned = set(re.findall(r"\bstage\d{2}\b", text))
    assert mentioned <= known, f"guide invents stages: {sorted(mentioned - known)}"
    # It must not introduce its own module numbering scheme.
    assert not re.search(r"^\|\s*RS\d\d", text, re.MULTILINE)


def test_guide_never_claims_learner_assessment_or_other_platform_execution():
    text = GUIDE.read_text(encoding="utf-8")
    assert "not_assessed" in text or "Not assessed" in text
    # It must state its platform scope honestly.
    assert "x86_64-pc-windows-msvc" in text
    assert "not run on Linux" in text or "not run" in text.lower()


def test_guide_records_the_locked_flag_rule_correctly():
    """`--locked` refuses a missing lockfile; it never regenerates one."""
    text = GUIDE.read_text(encoding="utf-8")
    assert "cargo generate-lockfile" in text
    assert "refuses" in text.lower()
    assert "regenerates a missing lockfile" in text, (
        "the corrected table must name the wrong advice it replaces"
    )


def test_guide_keeps_the_lockfile_in_the_copy_list():
    text = GUIDE.read_text(encoding="utf-8")
    block = text.split("Preserve:", 1)[1].split("```", 2)[1]
    assert "Cargo.lock" in block, "a reproducible copy keeps the lock"
    assert "target/" not in block.replace("Exclude `target/`", "")


def test_every_backticked_repository_path_in_the_guide_exists():
    """Same rule as the layout doc: a referenced path must be real."""
    text = GUIDE.read_text(encoding="utf-8")
    families = ("my_work/", "data/sample.txt", "data/iris_sepal_length_cm.txt")
    missing = []
    for token in sorted(set(re.findall(r"\]\(([^)#][^)]*)\)", text))):
        if token.startswith(("http", "#")):
            continue
        target = (GUIDE.parent / token).resolve()
        if not target.exists():
            missing.append(token)
    assert not missing, "guide links to paths that do not exist:\n  " + "\n  ".join(missing)
    assert families  # documented non-existent-by-design examples are exempt


def test_guide_does_not_claim_generated_files_are_hand_edited():
    text = GUIDE.read_text(encoding="utf-8")
    if "learning/workbooks" in text:
        assert "generated" in text.lower()


def test_learned_commands_the_guide_documents_still_exist():
    """Guard against documenting flags that the toolchain does not have."""
    text = GUIDE.read_text(encoding="utf-8")
    for flag in ("--offline", "--locked", "--all-targets", "--no-deps", "generate-lockfile"):
        assert flag in text, f"guide should still mention {flag}"
    # `cargo fmt --check` is spelled with a `--` separator; the bare form is a different flag.
    assert "cargo fmt --all -- --check" in text


def test_learning_area_still_has_no_extra_catalogues():
    catalogues = [
        p
        for p in (ROOT / "learning").rglob("*.json")
        if p.name in {"catalog.json", "labs.json"}
    ]
    assert not catalogues, f"learning/ must not own a catalogue: {catalogues}"
    stages = json.loads((ROOT / "curriculum/catalog.json").read_text(encoding="utf-8"))["stages"]
    assert len(stages) == 31
